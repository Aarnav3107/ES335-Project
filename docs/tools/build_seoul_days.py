"""
Builds js/seoul-days.js: one entry per day of the Seoul Bike Sharing year, with the daily rentals,
the season, and how many of that day's 24 hours land in train / validation / test under each of the
three splits from the notebook. The split code is the notebook's own (same random_state=42), and the
script stops if the recomputed coverage doesn't match the coverage already published in js/seoul-data.js.

Usage (from the beyond-the-model folder):
    python tools/build_seoul_days.py path/to/SeoulBikeData.csv .
"""
import json, sys
import numpy as np, pandas as pd
from sklearn.model_selection import train_test_split
csv, site = sys.argv[1], sys.argv[2]
raw = pd.read_csv(csv, encoding='unicode_escape')
# --- split 1: random rows, exactly as the notebook (dropna, drop Date, two train_test_splits) ---
df = raw.dropna(axis=0, subset=['Rented Bike Count']).copy()
idx = np.arange(len(df))
tr, te = train_test_split(idx, test_size=0.2, random_state=42)
tr, va = train_test_split(tr, test_size=0.25, random_state=42)
random_set = np.empty(len(df), dtype=object); random_set[tr] = 'Train'; random_set[va] = 'Validation'; random_set[te] = 'Test'
# --- split 2: chronological slicing ---
n = len(df); a, b = int(0.6 * n), int(0.8 * n)
chrono_set = np.array(['Train'] * a + ['Validation'] * (b - a) + ['Test'] * (n - b), dtype=object)
# --- split 3: season-stratified days ---
d2 = raw.copy(); d2['Date'] = pd.to_datetime(d2['Date'], dayfirst=True)
days = d2[['Date', 'Seasons']].drop_duplicates().reset_index(drop=True)
trd, rem = train_test_split(days, test_size=0.4, random_state=42, stratify=days['Seasons'])
vad, ted = train_test_split(rem, test_size=0.5, random_state=42, stratify=rem['Seasons'])
day_set = np.where(d2['Date'].isin(trd['Date']), 'Train', np.where(d2['Date'].isin(vad['Date']), 'Validation', 'Test'))
d2['random'], d2['chronological'], d2['day'] = random_set, chrono_set, day_set
# --- validate against the coverage already published on the site ---
src = open(f'{site}/js/seoul-data.js', encoding='utf-8').read()
pub = json.loads(src[src.index('{'):src.index('};') + 1])
ok = True
for split in ['random', 'chronological', 'day']:
    for c in pub['splits'][split]['coverage']:
        sub = d2[d2[split] == c['set']]
        mine = sub['Seasons'].value_counts().reindex(['Winter', 'Spring', 'Summer', 'Autumn']).fillna(0).astype(int).to_dict()
        same = mine == c['seasons'] and len(sub) == c['rows'] and abs(sub['Rented Bike Count'].mean() - c['mean']) < 1e-6
        ok &= same
        print(split, c['set'], 'rows', len(sub), 'match' if same else f'MISMATCH {mine} vs {c["seasons"]}')
assert ok, 'recomputed coverage does not match js/seoul-data.js'
print('coverage matches the published numbers')
# --- per-day summary for the timeline ---
out = []
for date, g in d2.groupby('Date', sort=True):
    entry = {'date': date.strftime('%Y-%m-%d'), 'season': g['Seasons'].iloc[0], 'bikes': int(g['Rented Bike Count'].sum())}
    for split in ['random', 'chronological', 'day']:
        counts = g[split].value_counts()
        entry[split] = [int(counts.get(s, 0)) for s in ['Train', 'Validation', 'Test']]
    out.append(entry)
print(len(out), out[0], out[-1])
open(f'{site}/js/seoul-days.js', 'w', encoding='utf-8').write(
    '/* Generated by tools/build_seoul_days.py from SeoulBikeData.csv using the notebook split code. */\nwindow.SEOUL_DAYS = '
    + json.dumps(out, separators=(',', ':')) + ';\n')
print('js/seoul-days.js written')
